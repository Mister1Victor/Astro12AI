def build_rider_waite() -> dict:
    """Колода Райдера-Уэйта: 78 карт, деканы, особое имя 2 Жезлов."""
    cards = []

    for cid, name, num, astro, kw, up, rev, desc in RW_MAJOR:
        cards.append({
            "id": cid, "name": name, "arcana": "major", "number": num,
            "image": f"{cid}.jpg", "astrology": astro, "keywords": kw,
            "upright": up, "reversed": rev, "description": desc,
        })

    for suit, ranks in RW_MINOR.items():
        for rank, (kw, up, rev) in ranks.items():
            rank_name, num = RANK_NAMES[rank]
            cid = f"{suit}_{rank}"
            name = RW_SPECIAL_NAMES.get(
                (suit, rank), f"{rank_name} {SUIT_GENITIVE[suit]}")
            cards.append({
                "id": cid, "name": name, "arcana": "minor", "suit": suit, "number": num,
                "image": f"{cid}.jpg", "astrology": DECANS[suit].get(rank, ""),
                "keywords": kw, "upright": up, "reversed": rev,
            })

    assert len(
        cards) == 78, f"Райдер-Уэйт: ожидалось 78 карт, получилось {len(cards)}"
    return {
        "id": "rider_waite",
        "name": "Таро Райдера-Уэйта",
        "author": "Артур Эдвард Уэйт",
        "description": "Классическая колода 1909 года. Эталон западной традиции Таро.",
        "cards": cards,
    }


