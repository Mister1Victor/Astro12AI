def build_deck() -> dict:
    """Собирает полную колоду Райдера-Уэйта (78 карт)."""
    cards = []

    # Старшие арканы
    for cid, name, num, astro, kw, up, rev, desc in MAJOR:
        cards.append({
            "id": cid, "name": name, "arcana": "major", "number": num,
            "image": f"{cid}.jpg", "astrology": astro, "keywords": kw,
            "upright": up, "reversed": rev, "description": desc,
        })

    # Младшие арканы
    for suit, ranks in MINOR.items():
        for rank, (kw, up, rev) in ranks.items():
            rank_name, num = RANK_NAMES[rank]
            cid = f"{suit}_{rank}"
            cards.append({
                "id": cid,
                "name": f"{rank_name} {SUIT_GENITIVE[suit]}",
                "arcana": "minor", "suit": suit, "number": num,
                "image": f"{cid}.jpg", "keywords": kw,
                "upright": up, "reversed": rev,
            })

    assert len(cards) == 78, f"Ожидалось 78 карт, получилось {len(cards)}"

    return {
        "id": "rider_waite",
        "name": "Таро Райдера-Уэйта",
        "author": "Артур Эдвард Уэйт",
        "description": "Классическая колода 1909 года. Эталон западной традиции Таро: символика, проверенная временем.",
        "cards": cards,
    }


def write_json(path: Path, data: dict, force: bool) -> bool:
    """Пишет JSON. Возвращает True, если файл записан."""
    if path.exists() and not force:
        print(f"⏭️  Уже существует (пропущено): {path}")
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print(f"✅ Создан: {path}")
    return True


