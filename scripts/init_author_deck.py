def build_author_numeric():
    """36 числовых карт по модифицированному Халдейскому ряду (планета в знаке)."""
    cards = []
    dec_idx = 0
    for sign_idx, sign in enumerate(SIGNS_ORDER):
        suit = SIGN_SUIT[sign]
        for d in range(3):
            card_num = NUM_CYCLE[(sign_idx * 3 + d) % 9]
            planet = CHALDEAN[dec_idx % 12]
            rank = str(card_num)
            thoth_name, keywords, upright, reversed_ = itd.THOTH_MINOR[suit][rank]
            title, esoteric = NUM_DATA[(suit, card_num)]
            cid = f"{suit}_{rank}"
            cards.append({
                "id": cid,
                "name": f"{title} ({card_num} {itd.SUIT_GENITIVE[suit]})",
                "arcana": "minor", "suit": suit, "number": card_num,
                "image": f"{cid}.jpg",
                "astrology": f"{planet} в {sign}",
                "keywords": keywords,
                "upright": upright,
                "reversed": reversed_,
                "description": f"{esoteric} {d + 1}-й декан знака {sign}.",
            })
            dec_idx += 1
    return cards


