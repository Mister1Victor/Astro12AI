def main():
    if not DECK.exists():
        print(f"❌ Файл не найден: {DECK}")
        print("   Сначала сгенерируйте колоду: python scripts/init_tarot_data.py")
        sys.exit(1)

    with open(DECK, encoding="utf-8") as f:
        deck = json.load(f)

    filled = 0
    processed_ids = set()
    for card in deck["cards"]:
        cid = card.get("id")
        if cid in CONTENT:
            processed_ids.add(cid)
            for field in FIELDS:
                if not str(card.get(field, "")).strip():
                    card[field] = CONTENT[cid][field]
                    filled += 1

    with open(DECK, "w", encoding="utf-8") as f:
        json.dump(deck, f, ensure_ascii=False, indent=2)

    print(
        f"✅ Заполнено полей: {filled} (карт обработано: {len(processed_ids)})")

    # Проверка: все ли карты в deck.json получили поля
    all_ids = {card.get("id") for card in deck["cards"]}
    missing = all_ids - processed_ids
    if missing:
        print(
            f"⚠️ Карты без контента ({len(missing)}): {sorted(missing)[:10]}...")
    extra = processed_ids - all_ids
    if extra:
        print(
            f"⚠️ Контент без карт в deck.json ({len(extra)}): {sorted(extra)[:10]}...")
    if not missing and not extra:
        print("🎉 Все карты Таро Тота обработаны полностью.")


if __name__ == "__main__":
    main()
