"""
Достоинства стихий (Elemental Dignities) для расклада «Динамический триплет».

Правила взаимодействия соседних карт:
- Дружественные (усиливают): Огонь+Воздух, Вода+Земля
- Враждебные (ослабляют/блокируют): Огонь+Вода, Воздух+Земля
- Нейтральные: Огонь+Земля, Вода+Воздух
- Однородные: удвоение энергии стихии
- Старшие Арканы: судьбоносная сила вне стихийных взаимодействий
"""

SUIT_ELEMENTS = {
    "wands": "Огонь",       # Жезлы: активность, энергия, страсть
    "swords": "Воздух",     # Мечи: интеллект, логика, конфликты, выбор
    "cups": "Вода",         # Кубки: эмоции, чувства, интуиция
    "pentacles": "Земля",   # Пентакли: материальный мир, деньги, стабильность
}

ELEMENT_MEANINGS = {
    "Огонь": "активность, энергия, страсть",
    "Воздух": "интеллект, логика, конфликты, выбор",
    "Вода": "эмоции, чувства, интуиция",
    "Земля": "материальный мир, деньги, стабильность",
}

FRIENDLY = {frozenset({"Огонь", "Воздух"}), frozenset({"Вода", "Земля"})}
HOSTILE = {frozenset({"Огонь", "Вода"}), frozenset({"Воздух", "Земля"})}

FRIENDLY_NOTES = {
    frozenset({"Огонь", "Воздух"}): "воздух раздувает огонь — идеи превращаются в действия",
    frozenset({"Вода", "Земля"}): "вода питает землю — эмоции дают материальный плод, стабильность",
}
HOSTILE_NOTES = {
    frozenset({"Огонь", "Вода"}): "вода тушит огонь — эмоции блокируют действия, или страсть гаснет",
    frozenset({"Воздух", "Земля"}): "воздух сушит землю, земля заземляет воздух — жёсткая логика мешает практическому росту",
}
NEUTRAL_NOTES = {
    frozenset({"Огонь", "Земля"}): "нейтрально-активные: огонь согревает землю, но может выжечь",
    frozenset({"Вода", "Воздух"}): "нейтрально-пассивные: туман, много мыслей и чувств, мало дела",
}


def card_element(card):
    """Стихия карты: младшие — по масти; старшие — None (судьбоносная сила)."""
    if getattr(card, "arcana", "minor") == "major":
        return None
    return SUIT_ELEMENTS.get(getattr(card, "suit", None))


def element_label(card) -> str:
    """Человекочитаемая стихия карты."""
    el = card_element(card)
    if el is None:
        return "Старший Аркан — судьбоносная сила"
    return f"{el} ({ELEMENT_MEANINGS[el]})"


def pair_dignity(card_a, card_b) -> str:
    """Достоинство стихий двух соседних карт."""
    el_a, el_b = card_element(card_a), card_element(card_b)

    if el_a is None and el_b is None:
        return ("Два Старших Аркана: редкое сочетание судьбоносных сил, "
                "ситуация ведётся высшими причинами.")

    if el_a is None or el_b is None:
        other_el = el_b if el_a is None else el_a
        return (f"Старший Аркан рядом со стихией '{other_el}': судьбоносная сила вне стихийных "
                f"взаимодействий, усиливает значимость того, с чем соседствует.")

    if el_a == el_b:
        return (f"Однородные стихии ({el_a}+{el_a}): удвоение энергии — избыток этой стихии, "
                f"усилены её сильные и теневые стороны.")

    pair = frozenset({el_a, el_b})
    if pair in FRIENDLY:
        return f"Дружественные: {el_a} и {el_b} усиливают друг друга ({FRIENDLY_NOTES[pair]})."
    if pair in HOSTILE:
        return f"Антагонисты: {el_a} и {el_b} ослабляют или блокируют друг друга ({HOSTILE_NOTES[pair]})."
    return f"Нейтральное взаимодействие: {NEUTRAL_NOTES[pair]}."


def triplet_dignities(drawn) -> list:
    """
    Анализ Динамического триплета (3 карты): стихии + вектор чтения + достоинства.
    drawn: [(карта, перевёрнута), ...]
    Возвращает список строк.
    """
    if len(drawn) < 3:
        return []
    (c1, _), (c2, _), (c3, _) = drawn[:3]
    return [
        "Вектор чтения: слева направо.",
        f"Карта 1 (ядро/суть): {c1.name} — {element_label(c1)}.",
        f"Карта 2 (модификатор/катализатор, влияет на карту 1): {c2.name} — {element_label(c2)}.",
        f"Карта 3 (вектор/итог, влияет на карту 2 и направляет к финалу): {c3.name} — {element_label(c3)}.",
        f"Взаимодействие 1→2: {pair_dignity(c1, c2)}",
        f"Взаимодействие 2→3: {pair_dignity(c2, c3)}",
    ]
